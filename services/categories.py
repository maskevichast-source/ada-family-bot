def format_category_list(categories: list[str]) -> str:
    return "\n".join(f"{index}. {name}" for index, name in enumerate(categories, start=1))


FALLBACK_EXPENSE_CATEGORY = "Обязательные платежи и прочее"
FALLBACK_INCOME_CATEGORY = "Кэшбэк и прочие поступления"


def normalize_category(raw: str | None, categories: list[str], fallback: str) -> str:
    if not raw:
        return fallback
    raw_norm = str(raw).strip().lower()
    if not raw_norm:
        return fallback
    aliases = {
        "алкоголь и табак": "Алкоголь, табак и энергетики",
        "прочие": "Обязательные платежи и прочее",
        "обязательные и прочие": "Обязательные платежи и прочее",
        "еда и продукты": "Еда и продукты",
        "транспорт и авто": "Транспорт и авто",
        "транспорт и автo": "Транспорт и авто",
    }
    if raw_norm in aliases:
        return aliases[raw_norm]
    for cat in categories:
        if cat.lower() == raw_norm:
            return cat
    for cat in categories:
        if raw_norm in cat.lower() or cat.lower() in raw_norm:
            return cat
    return fallback


def normalize_subcategory(raw: str | None, category: str | None, fallback: str = "") -> str:
    if not raw or not category:
        return fallback
    raw_sub = str(raw).strip()
    if not raw_sub:
        return fallback
    valid_subs = SUBCATEGORIES_MAP.get(category, [])
    if not valid_subs:
        return fallback
    for sub in valid_subs:
        if sub.lower() == raw_sub.lower():
            return sub
    for sub in valid_subs:
        if raw_sub.lower() in sub.lower() or sub.lower() in raw_sub.lower():
            return sub
    return valid_subs[0] if valid_subs else fallback


def validate_transaction_category_subcategory(category: str, subcategory: str) -> tuple[str, str]:
    norm_cat = normalize_category(category, EXPENSE_CATEGORIES, FALLBACK_EXPENSE_CATEGORY)
    valid_subs = SUBCATEGORIES_MAP.get(norm_cat, [])
    if not valid_subs:
        return norm_cat, ""
    if subcategory in valid_subs:
        return norm_cat, subcategory
    correct_cat = SUBCATEGORY_TO_CATEGORY.get(subcategory)
    if correct_cat and correct_cat != norm_cat:
        return correct_cat, subcategory
    return norm_cat, valid_subs[0]


def is_ambiguous_item(text: str) -> tuple[bool, list[str]]:
    """Проверить, является ли товар неоднозначным. Возвращает (is_ambiguous, alternatives)."""
    text_lower = str(text).lower()
    for item, alternatives in AMBIGUOUS_ITEMS.items():
        if item in text_lower:
            return True, alternatives
    return False, []


def get_time_context_hint(hour: int, weekday: int) -> str:
    """Вернуть подсказку о контексте на основе времени и дня недели.

    hour: 0-23, weekday: 0=Пн, 6=Вс
    """
    hints = []

    # Время суток
    if 6 <= hour < 10:
        hints.append("утро — дорога на работу, завтрак, энергетики")
    elif 10 <= hour < 12:
        hints.append("предобед — перекус, кофе")
    elif 12 <= hour < 15:
        hints.append("обед — еда вне дома, кафе, доставка")
    elif 15 <= hour < 18:
        hints.append("послеобед — покупки, продукты")
    elif 18 <= hour < 21:
        hints.append("вечер — дорога домой, ужин, продукты домой")
    elif 21 <= hour < 24:
        hints.append("ночь — вредные привычки, доставка, развлечения")
    else:
        hints.append("ночь/раннее утро — скорее вредные привычки")

    # День недели
    if weekday < 5:
        hints.append("будний день — работа, транспорт, обеды")
    else:
        hints.append("выходной — кафе, развлечения, продукты домой, ремонт")

    return "; ".join(hints)
