def format_category_list(categories: list[str]) -> str:
    """Пронумерованный список категорий для вставки в промпт."""
    return "\n".join(f"{index}. {name}" for index, name in enumerate(categories, start=1))


# Категории-«прочее» — то, во что нормализуется всё, что ИИ не смог
# уверенно определить или что вернулось не из списка (баг с чеком на
# сигареты, записанным как категория "Прочие", которой вообще нет в
# схеме, — как раз такой случай).
FALLBACK_EXPENSE_CATEGORY = "Обязательные платежи и прочее"
FALLBACK_INCOME_CATEGORY = "Кэшбэк и прочие поступления"


def normalize_category(raw: str | None, categories: list[str], fallback: str) -> str:
    """Привести произвольную строку категории от ИИ к одному из разрешённых значений.

    ИИ (текстовый или vision) иногда возвращает категорию не из списка —
    сокращает название, путает регистр или вовсе придумывает своё
    ("Прочие" вместо "Обязательные платежи и прочее"). Раньше такая
    строка сохранялась в таблицу как есть, ломая фильтры по категориям
    в лимитах, графике и сводках. Теперь любая запись гарантированно
    получает одно из значений из categories, либо fallback.
    """
    if not raw:
        return fallback
    raw_norm = str(raw).strip().lower()
    if not raw_norm:
        return fallback
    for cat in categories:
        if cat.lower() == raw_norm:
            return cat
    for cat in categories:
        if raw_norm in cat.lower() or cat.lower() in raw_norm:
            return cat
    return fallback
