def format_subcategory_dict(subs: dict) -> str:
    return "\n".join(f"- {cat}: {', '.join(sublist)}" for cat, sublist in subs.items())

def normalize_subcategory(category: str, raw_sub: str) -> str:
    valid_subs = STRICT_SUBCATEGORIES.get(category, ["Прочее"])
    if not raw_sub:
        return "Прочее"
    raw_norm = str(raw_sub).strip().lower()
    for sub in valid_subs:
        if raw_norm in sub.lower() or sub.lower() in raw_norm:
            return sub
    return "Прочее"

def normalize_necessity(raw_nec: str, category: str) -> str:
    val_str = str(raw_nec).strip().lower()
    nec_map = {
        "обязательное": "Need", "необходимое": "Need", "need": "Need", "нужное": "Need",
        "необязательное": "Want", "желание": "Want", "want": "Want", "хотелка": "Want"
    }
    for k, v in nec_map.items():
        if k in val_str:
            return v
    # Автораспределение, если ИИ пропустил
    need_cats = ["Еда и продукты", "Транспорт и авто", "Жильё и коммунальные услуги", 
                 "Связь и подписки", "Здоровье и медицина", "Обязательные платежи и прочее"]
    if any(c in str(category) for c in need_cats):
        return "Need"
    return "Want"

def normalize_strict_bank(raw_bank: str, resource: str) -> str:
    val_str = str(raw_bank).strip()
    if str(resource).strip().lower() == "наличные":
        return "Наличные"
    if not val_str or val_str.lower() in ["none", "nan", "не указан", ""]:
        return "Kaspi"  # Дефолтный банк для безнала
    for b in STRICT_BANKS:
        if b.lower() in val_str.lower():
            return b
    return "Kaspi"
